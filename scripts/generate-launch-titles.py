#!/usr/bin/env python3
"""Regenerates src/core/launchtitles.lua.

Usage: scripts/generate-launch-titles.py [page.html] [roms dir with <system>/gamelist.xml]

The page (default: example-data/launchtitles.html) is Gamicus' "List of video game console launch games", saved from a browser.
The roms dir (default: example-data) supplies ScreenScraper and RetroAchievements IDs.
"""
import html, os, re, sys

HTML = sys.argv[1] if len(sys.argv) > 1 else "example-data/launchtitles.html"
ROMS = sys.argv[2] if len(sys.argv) > 2 else 'example-data'

SYSTEMS = {
 "Atari 2600": "atari2600", "Intellivision": "intellivision", "ColecoVision": "colecovision", "Atari 5200": "atari5200",
 "SG-1000": "sg1000", "Famicom/Nintendo Entertainment System": "nes", "Famicom Disk System": "fds",
 "Sega Mark III/Sega Master System": "mastersystem", "Atari 7800": "atari7800",
 "NEC PC Engine/TurboGrafx-16/TurboGrafx": "pcengine", "NEC PC-Engine Super CD-ROM² / TurboGrafx-CD": "pcenginecd",
 "Sega Mega Drive/Genesis": "megadrive", "Sega Mega-CD": "segacd", "Sega 32X": "sega32x", "Super Famicom/SNES": "snes",
 "Neo Geo AES": "neogeo", "3DO Interactive Multiplayer": "3do", "Sega Saturn": "saturn", "Sony PlayStation": "psx",
 "Nintendo 64": "n64", "Atari Jaguar": "jaguar", "Sega Dreamcast": "dreamcast", "Sony PlayStation 2": "ps2",
 "Nintendo GameCube": "gamecube", "Microsoft Xbox": "xbox", "Xbox 360": "xbox360", "PlayStation 3": "ps3", "Wii": "wii",
 "Wii U": "wiiu", "Atari Lynx": "lynx", "Game Boy": "gb", "Sega Game Gear": "gamegear", "Virtual Boy": "virtualboy",
 "Game Boy Color": "gbc", "WonderSwan": "wswan", "Neo Geo Pocket Color": "ngpc", "WonderSwan Color": "wswanc",
 "Game Boy Advance": "gba", "Nintendo DS": "nds", "PlayStation Portable": "psp", "Nintendo 3DS": "3ds",
 "PlayStation Vita": "psvita", "Nintendo Switch": "switch",
}

def text(x): return html.unescape(re.sub(r'\s+', ' ', re.sub('<[^>]+>', '', x))).strip()

def parse(path):
    s = open(path, encoding='utf-8', errors='ignore').read()
    s = s[s.index('Home game consoles[]') if 'Home game consoles[]' in s else 0:]
    parts = re.split(r'(<h[2-5][^>]*>.*?</h[2-5]>)', s, flags=re.S)
    out = {}
    for i in range(1, len(parts), 2):
        system = SYSTEMS.get(text(parts[i]).replace('[]', '').replace('[ ]', '').strip())
        for region, ul in re.findall(r'<p>(.*?)</p>\s*<ul>(.*?)</ul>', parts[i + 1], re.S):
            if system:
                out.setdefault(system, []).append([text(li) for li in re.findall(r'<li>(.*?)</li>', ul, re.S)])
    return out
# Games that can't be played without a light gun, R.O.B., paddles or a driving controller.
PERIPHERAL = {"nes": {"Duck Hunt", "Gyromite", "Hogan's Alley", "Stack-Up", "Wild Gunman"},
              "mastersystem": {"Safari Hunt"}, "atari2600": {"Indy 500", "Street Racer", "Video Olympics"}}
# Other names the same game goes by in scraped gamelists, used only to look up IDs.
ALIASES = {("mastersystem", "Hang-On"): ["Hang-On & Safari Hunt"], ("mastersystem", "Teddy Boy Blues"): ["Teddy Boy"],
           ("dreamcast", "Sega Rally Championship 2"): ["Sega Rally 2"], ("dreamcast", "CART Flag to Flag"): ["Flag to Flag"],
           ("psx", "Kileak: The Blood"): ["Kileak: The DNA Imperative"]}
norm = lambda s: re.sub(r'[^a-z0-9]', '', html.unescape(s).lower())

def clean(title):
    if re.search(r'\((Demo|preloaded application|\d+ titles)\)', title, re.I): return None
    title = re.sub(r'\s*\([^)]*\)', '', title).replace('"', '').strip()
    return title or None

def library(system):
    p = os.path.join(ROMS, system, 'gamelist.xml')
    if not os.path.exists(p): return None
    games = []
    for attrs, body in re.findall(r'<game([^>]*)>(.*?)</game>', open(p, encoding='utf-8', errors='ignore').read(), re.S):
        n = re.search(r'<name>(.*?)</name>', body); lang = re.search(r'<lang>(.*?)</lang>', body)
        if lang and set(lang.group(1).split(',')) <= {'jp', 'ja'}: continue
        ss = re.search(r'id="(\d+)"', attrs) if 'name="ScreenScraper"' in body else None
        ra = re.search(r'<cheevosId>(\d+)</cheevosId>', body)
        games.append((norm(n.group(1) if n else ''), ss and int(ss.group(1)), ra and int(ra.group(1))))
    return games

def lua(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
out = ['-- Generated by scripts/generate-launch-titles.py; edit that script, not this file.',
       '-- Launch titles per console from all regions, from Gamicus\' "List of video game console launch games".',
       '-- Games that need a light gun, R.O.B., paddles or a driving controller are left out.',
       '-- Games match by ScreenScraper ID, then RetroAchievements ID, then normalized name;',
       '-- IDs come from scraped gamelists and are missing where no scraped copy was available.',
       'return {']
stats, unmatched = {}, []
for system, regions in parse(HTML).items():
    titles, seen = [], set()
    for names in regions:
        for raw in names:
            t = clean(raw)
            if t and t not in PERIPHERAL.get(system, ()) and norm(t) not in seen:
                seen.add(norm(t)); titles.append(t)
    games = library(system)
    key = system if system.isidentifier() else '[' + lua(system) + ']'
    out.append(f'  {key} = {{')
    ids = 0
    for t in titles:
        fields = [f'name = {lua(t)}']
        if games is not None:
            wanted = {norm(t)} | {norm(a) for a in ALIASES.get((system, t), [])}
            hit = next((g for g in games if g[0] in wanted), None)
            if hit:
                if hit[1]: fields.append(f'screenscraper = {hit[1]}')
                if hit[2]: fields.append(f'retroachievements = {hit[2]}')
                ids += 1
            else:
                unmatched.append(f'{system}: {t}')
        out.append('    { ' + ', '.join(fields) + ' },')
    out.append('  },')
    stats[system] = (len(titles), ids if games is not None else '-')
out.append('}')
open('src/core/launchtitles.lua', 'w').write('\n'.join(out) + '\n')
print(stats); print('total', sum(v[0] for v in stats.values()), 'with ids', sum(v[1] for v in stats.values() if v[1] != '-'))
print('NOT IN EXAMPLE LIBRARY:', '\n'.join(unmatched))
